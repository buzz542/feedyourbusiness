import { TREND_LABELS } from "@/server/rivals/view";
import { KIND_LABELS, type BuildGroups, type BuildTheme } from "./view";

/**
 * The Build tab as Markdown (docs/PLAN.md 4.6): the screen minus excerpts. Evidence posts appear as
 * links only, so no quote and no handle leaves the app (2.3.14).
 */
export function renderBuildReport(input: {
  week: string;
  productName: string;
  groups: BuildGroups;
}): string {
  const lines = [`# Build report, week of ${input.week}`, "", `Product: ${input.productName}`, ""];
  const section = (title: string, items: readonly BuildTheme[]) => {
    lines.push(`## ${title}`, "");
    if (items.length === 0) lines.push("Nothing this week.", "");
    for (const t of items) {
      lines.push(`### ${t.title}`, "");
      lines.push(`${KIND_LABELS[t.kind]} · ${t.count} posts · ${TREND_LABELS[t.trend]}`, "");
      lines.push(t.summary, "");
      if (t.evidence.length > 0)
        lines.push(...t.evidence.map((e, i) => `- [Post ${i + 1}](${e.url})`), "");
    }
  };
  section("Themes this week", input.groups.themes);
  section("Wished it existed", input.groups.wishes);
  section("What to build next", input.groups.next);
  lines.push("Say you built it, if you reply to any of these posts.");
  lines.push("Generated by AskedFor from public posts. Summaries are our own words.");
  return lines.join("\n");
}
