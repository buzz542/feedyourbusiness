import { TREND_LABELS, type Scorecard } from "./view";

/**
 * The week's rival report as Markdown (docs/PLAN.md 4.5): counts, issues, trends and our own
 * summaries. No handles and no post excerpts (2.3.14): it is built only from aggregates.
 */
export function renderRivalReport(input: {
  week: string;
  productName: string;
  scorecards: readonly Scorecard[];
  fixes: readonly { title: string; summary: string }[];
}): string {
  const lines = [`# Rival report, week of ${input.week}`, "", `Product: ${input.productName}`, ""];
  if (input.scorecards.length === 0)
    lines.push("No complaints about tracked rivals this week.", "");
  for (const card of input.scorecards) {
    lines.push(`## ${card.name}`, "");
    lines.push(`- Complaints this week: ${card.complaints}`);
    lines.push(`- People looking to switch: ${card.switching}`);
    for (const issue of card.issues)
      lines.push(`- ${issue.label}: ${issue.complaints} (${TREND_LABELS[issue.trend]})`);
    lines.push("");
    for (const s of card.summaries) lines.push(`${s.text}`, "");
  }
  if (input.fixes.length > 0) {
    lines.push("## What you could fix", "");
    for (const f of input.fixes) lines.push(`- **${f.title}**: ${f.summary}`);
    lines.push("");
  }
  lines.push("Generated by AskedFor from public posts. Summaries are our own words.");
  return lines.join("\n");
}
